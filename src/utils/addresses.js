function _env(key) {
  try {
    if (typeof import.meta !== "undefined" && import.meta.env)
      return import.meta.env[key];
  } catch (err) {
    console.debug("addresses._env import.meta lookup failed", key, err);
  }
  try {
    if (typeof process !== "undefined" && process.env) return process.env[key];
  } catch (err) {
    console.debug("addresses._env process.env lookup failed", key, err);
  }
  return undefined;
}

function _envAddr(key, fallback) {
  const keys = [key, `${key}_ADDRESS`, `${key}_ADDR`, `ADDR_${key}`].map(
    (k) => `VITE_${k}`,
  );
  for (const k of keys) {
    const v = _env(k);
    if (v && typeof v === "string" && v.trim()) return v.trim();
  }
  return fallback;
}

function _sameAddr(a, b) {
  if (!a || !b) return false;
  return String(a).toLowerCase() === String(b).toLowerCase();
}

