// If only BIGGI is overridden, mirror it into BIGGI_TOKEN (and vice versa).
const overrideBiggi = _envAddr("BIGGI", null);
const overrideBiggiToken = _envAddr("BIGGI_TOKEN", null);
if (overrideBiggi && !overrideBiggiToken) {
  ADDR.BIGGI_TOKEN = overrideBiggi;
}
if (overrideBiggiToken && !overrideBiggi) {
  ADDR.BIGGI = overrideBiggiToken;
}

// Legacy env support: VITE_ADDR_BiggiREWARDSReader -> map into the canonical reader slots.
const legacyBiggiREWARDSReader = _envAddr("BiggiREWARDSReader", null);
if (legacyBiggiREWARDSReader) {
  ADDR.BIGGI_REWARDS_READER = legacyBiggiREWARDSReader;
  ADDR.COLLECTION_REWARDS_READER = legacyBiggiREWARDSReader;
  ADDR.BiggiREWARDSReader = legacyBiggiREWARDSReader;
}

// Canonicalize: main points to VRF COLLECTION, main2 points to public COLLECTION.
if (ADDR.COLLECTION_VRF && !_sameAddr(ADDR.MAIN, ADDR.COLLECTION_VRF)) {
  ADDR.MAIN = ADDR.COLLECTION_VRF;
}
if (ADDR.COLLECTION_PUBLIC && !_sameAddr(ADDR.MAIN2, ADDR.COLLECTION_PUBLIC)) {
  ADDR.MAIN2 = ADDR.COLLECTION_PUBLIC;
}

// Enforce allowlist: only these addresses are used by the frontend.
const ALLOWED_ADDRS = { ...ADDR };

const KEEP_KEYS = new Set(["DEPLOY_BLOCK"]);
for (const key of Object.keys(ADDR)) {
  if (KEEP_KEYS.has(key)) continue;
  if (Object.prototype.hasOwnProperty.call(ALLOWED_ADDRS, key)) {
    ADDR[key] = ALLOWED_ADDRS[key];
  } else {
    ADDR[key] = "";
  }
}

